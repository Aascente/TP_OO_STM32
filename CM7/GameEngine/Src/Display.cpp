Display::Display(uint16_t* externalBuffer) {
    if (externalBuffer != nullptr) {
        framebuffer = externalBuffer;
        allocatedInternally = false;
    } else {
#if defined(USE_STM32H747I_DISCO)
        framebuffer = reinterpret_cast<uint16_t*>(ARCADE_OFFSCREEN_FB_ADDR);
#else
        framebuffer = internal_sram_framebuffer;
#endif
        allocatedInternally = false;
    }
}

Display::~Display() {}

void Display::init() {
    clear(COLOR_BLACK);
#if defined(USE_STM32H747I_DISCO)
    uint32_t fbAddr = LCD_LAYER_0_ADDRESS;
    uint32_t totalPixels = LCD_DEFAULT_WIDTH * LCD_DEFAULT_HEIGHT;
    if (Lcd_Ctx[0].PixelFormat == LCD_PIXEL_FORMAT_RGB565) {
        volatile uint16_t* lcd = reinterpret_cast<volatile uint16_t*>(fbAddr);
        for (uint32_t i = 0; i < totalPixels; ++i) {
            lcd[i] = 0x0000U;
        }
        SCB_CleanDCache_by_Addr(reinterpret_cast<uint32_t*>(fbAddr), totalPixels * 2U);
    } else {
        volatile uint32_t* lcd = reinterpret_cast<volatile uint32_t*>(fbAddr);
        for (uint32_t i = 0; i < totalPixels; ++i) {
            lcd[i] = 0xFF000000U;
        }
        SCB_CleanDCache_by_Addr(reinterpret_cast<uint32_t*>(fbAddr), totalPixels * 4U);
    }
    __DSB();
#endif
}

void Display::clear(uint16_t color) {
    for (int i = 0; i < DISPLAY_WIDTH * DISPLAY_HEIGHT; ++i) {
        framebuffer[i] = color;
    }
}

void Display::drawPixel(int x, int y, uint16_t color) {
    if (x >= 0 && x < DISPLAY_WIDTH && y >= 0 && y < DISPLAY_HEIGHT) {
        framebuffer[y * DISPLAY_WIDTH + x] = color;
    }
}

void Display::drawRect(int x, int y, int w, int h, uint16_t color) {
    for (int i = x; i < x + w; ++i) {
        drawPixel(i, y, color);
        drawPixel(i, y + h - 1, color);
    }
    for (int j = y; j < y + h; ++j) {
        drawPixel(x, j, color);
        drawPixel(x + w - 1, j, color);
    }
}

void Display::fillRect(int x, int y, int w, int h, uint16_t color) {
    int startX = x < 0 ? 0 : x;
    int endX = (x + w > DISPLAY_WIDTH) ? DISPLAY_WIDTH : x + w;
    int startY = y < 0 ? 0 : y;
    int endY = (y + h > DISPLAY_HEIGHT) ? DISPLAY_HEIGHT : y + h;

    for (int j = startY; j < endY; ++j) {
        int rowIdx = j * DISPLAY_WIDTH;
        for (int i = startX; i < endX; ++i) {
            framebuffer[rowIdx + i] = color;
        }
    }
}

void Display::drawSprite(int x, int y, const Sprite& sprite) {
    int sw = sprite.width;
    int sh = sprite.height;
    const uint16_t* data = sprite.data;

    for (int j = 0; j < sh; ++j) {
        int py = y + j;
        if (py < 0 || py >= DISPLAY_HEIGHT) continue;
        int rowIdx = py * DISPLAY_WIDTH;
        int sRowIdx = j * sw;

        for (int i = 0; i < sw; ++i) {
            int px = x + i;
            if (px < 0 || px >= DISPLAY_WIDTH) continue;
            uint16_t col = data[sRowIdx + i];
            if (col != CHROMA_KEY) {
                framebuffer[rowIdx + px] = col;
            }
        }
    }
}

void Display::drawGradientBackground(uint16_t topColor, uint16_t botColor, bool drawGrid, int gridSize) {
    int rTop = (topColor >> 11) & 0x1F;
    int gTop = (topColor >> 5) & 0x3F;
    int bTop = topColor & 0x1F;

    int rBot = (botColor >> 11) & 0x1F;
    int gBot = (botColor >> 5) & 0x3F;
    int bBot = botColor & 0x1F;

    for (int y = 0; y < DISPLAY_HEIGHT; ++y) {
        int r = rTop + ((rBot - rTop) * y) / (DISPLAY_HEIGHT - 1);
        int g = gTop + ((gBot - gTop) * y) / (DISPLAY_HEIGHT - 1);
        int b = bTop + ((bBot - bTop) * y) / (DISPLAY_HEIGHT - 1);
        uint16_t base = (r << 11) | (g << 5) | b;

        // Darker grid color
        int rGrid = (r > 3) ? r - 3 : 0;
        int gGrid = (g > 6) ? g - 6 : 0;
        int bGrid = (b > 3) ? b - 3 : 0;
        uint16_t gridCol = (rGrid << 11) | (gGrid << 5) | bGrid;

        int rowIdx = y * DISPLAY_WIDTH;
        bool isYGrid = drawGrid && (y % gridSize == 0);

        for (int x = 0; x < DISPLAY_WIDTH; ++x) {
            // 3px outer border
            if (x < 3 || x >= DISPLAY_WIDTH - 3 || y < 3 || y >= DISPLAY_HEIGHT - 3) {
                framebuffer[rowIdx + x] = 0x18E3; // Dark border wall
            } else if (drawGrid && (isYGrid || (x % gridSize == 0))) {
                framebuffer[rowIdx + x] = gridCol;
            } else {
                framebuffer[rowIdx + x] = base;
            }
        }
    }
}

void Display::drawChar(int x, int y, char c, uint16_t color, uint16_t bg, int scale) {
    if (c < 32 || c > 127) c = '?';
    const uint8_t* glyph = font8x8[c - 32];

    for (int r = 0; r < 8; ++r) {
        uint8_t row = glyph[r];
        for (int b = 0; b < 8; ++b) {
            bool pixelOn = (row & (0x80 >> b)) != 0;
            if (pixelOn) {
                if (scale == 1) drawPixel(x + b, y + r, color);
                else fillRect(x + b * scale, y + r * scale, scale, scale, color);
            } else if (bg != CHROMA_KEY) {
                if (scale == 1) drawPixel(x + b, y + r, bg);
                else fillRect(x + b * scale, y + r * scale, scale, scale, bg);
            }
        }
    }
}

void Display::drawString(int x, int y, const char* str, uint16_t color, uint16_t bg, int scale) {
    if (!str) return;
    int curX = x;
    while (*str) {
        if (*str == '\n') {
            y += 8 * scale + 2;
            curX = x;
        } else {
            drawChar(curX, y, *str, color, bg, scale);
            curX += 8 * scale;
        }
        str++;
    }
}

void Display::present() {
#if defined(USE_STM32H747I_DISCO)
    uint32_t fbAddr = LCD_LAYER_0_ADDRESS;
    const int lcdWidth = LCD_DEFAULT_WIDTH; // 800
    const int xOffset = (lcdWidth - DISPLAY_WIDTH) / 2; // 160px center offset

    if (Lcd_Ctx[0].PixelFormat == LCD_PIXEL_FORMAT_RGB565) {
        volatile uint16_t* lcd = reinterpret_cast<volatile uint16_t*>(fbAddr);
        for (int y = 0; y < DISPLAY_HEIGHT; ++y) {
            const uint16_t* src = &framebuffer[y * DISPLAY_WIDTH];
            volatile uint16_t* dst = &lcd[y * lcdWidth + xOffset];
            for (int x = 0; x < DISPLAY_WIDTH; ++x) {
                dst[x] = src[x];
            }
        }
        SCB_CleanDCache_by_Addr(reinterpret_cast<uint32_t*>(fbAddr), lcdWidth * LCD_DEFAULT_HEIGHT * 2U);
    } else {
        // BSP_LCD_Init defaults to LCD_PIXEL_FORMAT_RGB888 (LTDC ARGB8888)
        volatile uint32_t* lcd = reinterpret_cast<volatile uint32_t*>(fbAddr);
        for (int y = 0; y < DISPLAY_HEIGHT; ++y) {
            const uint16_t* src = &framebuffer[y * DISPLAY_WIDTH];
            volatile uint32_t* dst = &lcd[y * lcdWidth + xOffset];
            for (int x = 0; x < DISPLAY_WIDTH; ++x) {
                uint32_t c = src[x];
                dst[x] = (((((c >> 11U) & 0x1FU) * 527U + 23U) >> 6U) << 16U) |
                         (((((c >> 5U)  & 0x3FU) * 259U + 33U) >> 6U) << 8U)  |
                         (((( c         & 0x1FU) * 527U + 23U) >> 6U))        |
                         0xFF000000U;
            }
        }
        SCB_CleanDCache_by_Addr(reinterpret_cast<uint32_t*>(fbAddr), lcdWidth * LCD_DEFAULT_HEIGHT * 4U);
    }
    __DSB();
#endif
}
